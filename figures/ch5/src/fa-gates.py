from style import *

with schemdraw.Drawing(show=False) as d:
    x1 = gate(d, 'Xor', (-2, 0.5),  'XOR')
    a1 = gate(d, 'And', (-2, -2.5), 'AND')
    x2 = gate(d, 'Xor', (2, 0.75),  'XOR')
    a2 = gate(d, 'And', (2, -1.5),  'AND')
    o1 = gate(d, 'Or',  (5, -2.0),  'OR')

    P = anch(x1, 'out')
    wire(d, (-6, 1), (-2.6, 1))
    wire(d, (-6, 0), (-2.4, 0))
    wire(d, (-6, -1), (1.0, -1))
    lbl(d, (-6.1, 1), 'A'); lbl(d, (-6.1, 0), 'B'); lbl(d, (-6.1, -1), 'C$_{in}$')

    dot(d, (-2.8, 1))
    wire(d, (-2.6, 1), (-2.6, 0.75), anch(x1, 'in1'))
    wire(d, (-2.8, 1), (-2.8, -2.25), anch(a1, 'in1'))
    dot(d, (-2.2, 0))
    wire(d, (-2.4, 0), (-2.4, 0.25), anch(x1, 'in2'))
    wire(d, (-2.2, 0), (-2.2, -2.75), anch(a1, 'in2'))
    wire(d, P, (0.6, P[1])); dot(d, (0.6, P[1]))
    wire(d, (0.6, P[1]), (0.6, anch(x2,'in1')[1]), anch(x2, 'in1'))
    wire(d, (0.6, P[1]), (0.6, anch(a2,'in1')[1]), anch(a2, 'in1'))
    dot(d, (1.0, -1))
    wire(d, (1.0, -1), (1.0, anch(x2,'in2')[1]), anch(x2, 'in2'))
    wire(d, (1.0, -1), (1.0, anch(a2,'in2')[1]), anch(a2, 'in2'))
    wire(d, anch(a2,'out'), (4.6, anch(a2,'out')[1]), (4.6, anch(o1,'in1')[1]), anch(o1,'in1'))
    wire(d, anch(a1,'out'), (4.6, anch(a1,'out')[1]), (4.6, anch(o1,'in2')[1]), anch(o1,'in2'))
    wire(d, anch(x2,'out'), (7.9, anch(x2,'out')[1]))
    wire(d, anch(o1,'out'), (7.9, anch(o1,'out')[1]))
    lbl(d, (8.0, anch(x2,'out')[1]), 'Sum', loc='right')
    lbl(d, (8.0, anch(o1,'out')[1]), 'C$_{out}$', loc='right')
    d.save('fa-gates.png', dpi=220)
